// Downloads the latest PHP 8.3 Windows x64 *thread-safe* build, keeps only the extensions
// ViLoCare needs, writes a php.ini, and fetches the VC++ redistributable for the installer.
// Output: resources/php/ and build/vc_redist.x64.exe (both git-ignored).
const fs = require('fs');
const path = require('path');
const https = require('https');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const PHP_SERIES = '8.3';
const root = path.join(__dirname, '..');
const phpDir = path.join(root, 'resources', 'php');
const tmp = path.join(root, '.tmp-php');

// Extensions that are not compiled into the Windows build. pdo_pgsql/pgsql are deliberately left out.
const EXTENSIONS = ['curl', 'fileinfo', 'gd', 'intl', 'mbstring', 'openssl', 'pdo_sqlite', 'sqlite3', 'zip'];

function get(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': 'vilocare-build' } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return resolve(get(new URL(res.headers.location, url).href));
      }
      if (res.statusCode !== 200) return reject(new Error(`${url} -> HTTP ${res.statusCode}`));
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks)));
    }).on('error', reject);
  });
}

async function main() {
  // An older download without opcache is re-fetched, so an installer is never built without it.
  const hasPhp = fs.existsSync(path.join(phpDir, 'php.exe'));
  const hasOpcache = fs.existsSync(path.join(phpDir, 'ext', 'php_opcache.dll'));
  if (hasPhp && hasOpcache && !process.argv.includes('--force')) {
    console.log('PHP already present (use --force to re-download).');
  } else {
    const releases = JSON.parse((await get('https://windows.php.net/downloads/releases/releases.json')).toString());
    const rel = releases[PHP_SERIES];
    const build = rel && rel['ts-vs16-x64'];
    if (!build) throw new Error(`No ts-vs16-x64 build found for PHP ${PHP_SERIES}`);
    console.log(`Downloading PHP ${rel.version} (${build.zip.path})...`);
    const zip = await get(`https://windows.php.net/downloads/releases/${build.zip.path}`);
    const sha = crypto.createHash('sha256').update(zip).digest('hex');
    if (build.zip.sha256 && sha !== build.zip.sha256.toLowerCase()) throw new Error('PHP zip checksum mismatch');

    fs.rmSync(tmp, { recursive: true, force: true });
    fs.mkdirSync(tmp, { recursive: true });
    const zipFile = path.join(tmp, 'php.zip');
    fs.writeFileSync(zipFile, zip);
    fs.rmSync(phpDir, { recursive: true, force: true });
    fs.mkdirSync(phpDir, { recursive: true });
    execFileSync('tar', ['-xf', zipFile, '-C', phpDir], { stdio: 'inherit' });
    fs.rmSync(tmp, { recursive: true, force: true });

    // Prune: keep php.exe + DLLs + the needed extensions only.
    // php_opcache.dll comes from the same zip as php.exe, so the two always match (it loads via zend_extension).
    const keepExt = new Set([...EXTENSIONS.map((e) => `php_${e}.dll`), 'php_opcache.dll']);
    const extDir = path.join(phpDir, 'ext');
    for (const f of fs.readdirSync(extDir)) {
      if (!keepExt.has(f)) fs.rmSync(path.join(extDir, f), { force: true });
    }
    for (const f of ['php-cgi.exe', 'phpdbg.exe', 'php-win.exe', 'php8embed.lib', 'php8phpdbg.dll']) {
      fs.rmSync(path.join(phpDir, f), { force: true });
    }
    for (const d of ['dev', 'extras', 'lib']) fs.rmSync(path.join(phpDir, d), { recursive: true, force: true });

    const ini = [
      '; ViLoCare bundled PHP configuration (generated by scripts/fetch-php.js)',
      'memory_limit = 512M',
      'display_errors = Off',
      'log_errors = On',
      'variables_order = "EGPCS"',
      'date.timezone = Africa/Juba',
      'upload_max_filesize = 8M',
      'post_max_size = 10M',
      'opcache.enable_cli = 0',
      '',
      '; Opcache: the web server is one long-lived process, so compiled PHP is kept between requests.',
      '; Production settings: files are replaced only by an update, which restarts PHP, so timestamps are not re-checked.',
      'zend_extension=php_opcache.dll',
      'opcache.enable = 1',
      'opcache.memory_consumption = 128',
      'opcache.interned_strings_buffer = 16',
      'opcache.max_accelerated_files = 10000',
      'opcache.validate_timestamps = 0',
      'opcache.save_comments = 1',
      '; JIT is off: it brings nothing for this I/O-bound app and adds crash risk.',
      'opcache.jit = disable',
      'opcache.jit_buffer_size = 0',
      '',
      ...EXTENSIONS.map((e) => `extension=${e}`),
      '',
    ].join('\r\n');
    fs.writeFileSync(path.join(phpDir, 'php.ini'), ini);
    console.log(`PHP ${rel.version} ready in resources/php`);
  }

  const redist = path.join(root, 'build', 'vc_redist.x64.exe');
  if (!fs.existsSync(redist)) {
    console.log('Downloading VC++ redistributable...');
    fs.mkdirSync(path.dirname(redist), { recursive: true });
    fs.writeFileSync(redist, await get('https://aka.ms/vs/17/release/vc_redist.x64.exe'));
  }
}

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
